import { createHash, randomUUID } from "node:crypto";
import { chmod, writeFile } from "node:fs/promises";
import { basename } from "node:path";
import { settings, isMapsURL, isMapsImageCancellation, resourceKind, mapsScenarios, mapsTestFiles, mapsAllocation, plannedAllocation, assertRunnerPolicy } from "./safety.mjs";
