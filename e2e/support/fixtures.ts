import type { Envelope, Snapshot } from "./types";

const env = settings(true);
const lobbySocketURL = new URL(`${env.backend}/lobbySocket`);
lobbySocketURL.protocol = "ws:";
const networkMessage = /websocket|failed to fetch|networkerror|err_internet_disconnected|err_network_changed|connection (closed|lost)/i;
const providerMessage =
    /Google Maps.*(?:error|failed|quota|billing|denied|not authorized)|(?:OverQuota|OverQueryLimit|BillingNotEnabled|InvalidKey|RefererNotAllowed|ApiNotActivated)MapError/i;
const gameIdentity = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
type Diagnostic = {
    actor: number;
    kind: string;
    category: string;
    expected: boolean;
    fingerprint?: string;
    status?: number;
    afterHalt?: boolean;
    networkCode?: string;
    requestType?: string;
};

// Test bookkeeping only, shared across BOTH paid files in the one worker.
// No decrement/reset on selector failures, cleanup, or a new BrowserRun.
const paidBudget = {
    started: new Set<string>(),
    viewGrants: new Set<string>(),
    acceptedPermits: 0,
    rejectionPermits: 0,
    reservedGrants: 0,
    sdkRequests: 0,
    halted: false,
};

declare global {
    interface Window {
        __geobattlesE2EPermitStart: () => void;
        __geobattlesE2EProbeStart: () => void;
        __geobattlesE2EHaltStarts: () => void;
    }
}

export class Actor {
    events: Envelope[] = [];
    generation = 0;
    startCommands = 0;
    authRequests = 0;
    documentRequests = 0;
    mainFrameNavigations = 0;
    offline = false;
    navigating = false;
    closing = false;
    constructor(
        public context: BrowserContext,
        public page: Page,
        public name: string,
        public index: number
    ) {}
    mark() {
        return this.events.length;
    }
    get latest(): Snapshot | undefined {
        return [...this.events].reverse().find((event) => event.payload?.lobby)?.payload?.lobby;
    }
    get phase() {
        return [...this.events]
            .reverse()
            .map((event) => event.payload?.phase ?? event.payload?.lobby?.phase)
            .find(Boolean);
    }
    get players() {
        return (
            [...this.events]
                .reverse()
                .map((event) => event.payload?.players ?? event.payload?.lobby?.playerList)
                .find(Boolean) ?? {}
        );
    }
    get id(): string {
        const row = Object.entries(this.latest?.playerList ?? {}).find(([, player]) => player.name === this.name);
        if (!row) throw new Error("The real joined snapshot has not identified this guest");
        return row[0];
    }
    row(name = this.name) {
        // Display names are generated by this fixture and contain no selector metacharacters.
        return this.page.locator(`[data-testid="player-row"][data-player-name="${name}"]`);
    }
    async event(type: string, predicate: (event: Envelope) => boolean = () => true, after = 0, timeout = 15_000): Promise<Envelope> {
        const find = () => this.events.slice(after).find((event) => event.type === type && predicate(event));
        await expect.poll(() => !!find(), { message: `Expected a real ${type} socket event`, timeout }).toBe(true);
        return find()!;
    }
    async snapshot(predicate: (snapshot: Snapshot) => boolean, after = 0, timeout = 15_000): Promise<Snapshot> {
        const find = () => this.events.slice(after).find((event) => event.payload?.lobby && predicate(event.payload.lobby))?.payload?.lobby;
        await expect.poll(() => !!find(), { message: "Expected an authoritative membership snapshot", timeout }).toBe(true);
        return find()!;
    }
    async setOffline(value: boolean) {
        // Keep the diagnostic window open until a real recovery acknowledgement, not merely setOffline(false).
        if (value) this.offline = true;
        await this.context.setOffline(value);
    }
    async reload() {
        this.navigating = true;
        try {
            await this.page.reload({ waitUntil: "domcontentloaded" });
        } finally {
            this.navigating = false;
        }
    }
}

class BrowserRun {
    actors: Actor[] = [];
    contexts = new Set<BrowserContext>();
    networkGuard?: Awaited<ReturnType<typeof startNetworkGuard>>;
    diagnostics: Diagnostic[] = [];
    started = new Set<string>();
    viewGrants = new Set<string>();
    sdkRequests = 0;
    startPermits = 0;
    halted = false;
    acceptedPermits = 0;
    rejectionPermits = 0;
    reservedGrants = 0;
    currentGameId?: string;
    currentRound = 0;
    pendingStart?: { round: number };
    pendingRejection?: Actor;
    roundSequences = new Map<string, number>();
    plan?: (typeof mapsScenarios)[keyof typeof mapsScenarios];
    sdkFailure?: { actor: Actor; request?: Request; deadline: number; requestFailed: boolean; consoleError: boolean; diagnosticsClosed: boolean; resumed: boolean };
    constructor(
        public info: TestInfo,
        public newContext: (mobile: boolean, proxyServer: string) => Promise<BrowserContext>,
        public paid: boolean
    ) {
        if (paid) this.plan = mapsScenarios[basename(info.file) as keyof typeof mapsScenarios];
    }

    async startNetworkGuard() {
        this.networkGuard = await startNetworkGuard({
            frontend: env.frontend!,
            backend: env.backendOrigin, // Guard accepts origins only, never an API path.
            paid: this.paid,
            isHalted: () => this.halted || (this.paid && paidBudget.halted),
            onViolation: (category: string) => {
                this.diagnostics.push({ actor: -1, kind: "network-guard", category, expected: false });
                this.halt();
            },
        });
    }

    async close() {
        for (const actor of this.actors) actor.closing = true;
        try {
            // Include contexts whose actor setup/newPage failed before registration.
            const closed = await Promise.allSettled([...this.contexts].map((context) => context.close()));
            if (closed.some((result) => result.status === "rejected")) throw new Error("An owned browser context did not close cleanly");
        } finally {
            await this.networkGuard?.close();
        }
    }

    halt() {
        if (this.halted) return;
        this.halted = true;
        if (this.paid) paidBudget.halted = true;
        this.networkGuard?.halt();
        for (const actor of this.actors) void actor.page.evaluate(() => window.__geobattlesE2EHaltStarts?.()).catch(() => {});
    }

    record(actor: Actor, kind: string, category: string, expected = false, message?: string, status?: number, networkCode?: string, requestType?: string) {
        // Fingerprints permit deduplication without writing the original message/stack/URL.
        this.diagnostics.push({
            actor: actor.index,
            kind,
            category,
            expected,
            afterHalt: this.halted,
            ...(message ? { fingerprint: createHash("sha256").update(message).digest("hex").slice(0, 12) } : {}),
            ...(status ? { status } : {}),
            ...(networkCode ? { networkCode } : {}),
            ...(requestType ? { requestType } : {}),
        });
        if (!expected && kind !== "console-warning") this.halt();
    }

    failFirstMapsSDK(actor: Actor) {
        this.assertHealthy();
        expect(this.paid && env.maps).toBe(true);
        expect(basename(this.info.file)).toBe("game.maps.spec.ts");
        expect(actor === this.actors[1]).toBe(true); // Only the peer in the first paid scenario.
        expect(actor.phase).toBe("WAITING");
        expect(this.acceptedPermits).toBe(0);
        expect(this.sdkRequests).toBe(0);
        expect(this.sdkFailure, "Only one deliberate initial SDK failure is allocated").toBeUndefined();
        this.sdkFailure = { actor, deadline: 0, requestFailed: false, consoleError: false, diagnosticsClosed: false, resumed: false };
    }

    private sdkFailureInterval(actor: Actor) {
        const failure = this.sdkFailure;
        return failure?.actor === actor && failure.request && !failure.diagnosticsClosed && Date.now() <= failure.deadline ? failure : undefined;
    }

    async finishMapsSDKFailure(actor: Actor) {
        const failure = this.sdkFailure;
        expect(failure?.actor === actor).toBe(true);
        expect(failure?.diagnosticsClosed).toBe(false);
        await expect.poll(() => failure?.requestFailed, { message: "The one real SDK script must have failed through native routing", timeout: 12_000 }).toBe(true);
        await expect(actor.page.getByTestId("maps-recovery")).toBeVisible();
        await expect(actor.page.getByTestId("maps-recovery").getByRole("status")).toHaveText("Map unavailable. Your round continues.");
        await expect(actor.page.getByTestId("maps-recovery").getByRole("button", { name: "Retry map", exact: true })).toBeEnabled();
        expect(!!this.sdkFailureInterval(actor), "Deliberate diagnostics expire after 12 seconds, never across the retry").toBe(true);
        failure!.diagnosticsClosed = true; // End on the peer's visible failure, not on the healthy player's loading time.
        this.assertHealthy();
    }

    resumeMapsSDK(actor: Actor) {
        const failure = this.sdkFailure;
        expect(failure?.actor === actor && failure.diagnosticsClosed && !failure.resumed).toBe(true);
        this.assertHealthy();
        failure!.resumed = true; // No diagnostic exemption during/after the real Retry map click.
    }

    async actor(label: string, mobile = false): Promise<Actor> {
        expect(this.halted || (this.paid && paidBudget.halted), "A halted invocation cannot create more players").toBe(false);
        expect(this.networkGuard, "The native destination boundary must exist before any actor context").toBeDefined();
        const context = await this.newContext(mobile, this.networkGuard!.server);
        this.contexts.add(context);
        const page = await context.newPage();
        const actor = new Actor(context, page, `E2E-${label.slice(0, 1)}-${randomUUID().slice(0, 8)}`, this.actors.length);
        this.actors.push(actor);
        if (mobile) {
            expect(page.viewportSize()).toEqual({ width: 390, height: 844 });
            expect(await page.evaluate(() => matchMedia("(pointer: coarse)").matches), "Responsive contexts expose the configured coarse pointer").toBe(true);
            // Native Firefox exposes the coarse-pointer override but reports
            // zero maxTouchPoints; do not fake navigator/device capabilities.
            if (context.browser()?.browserType().name() === "chromium") {
                expect(await page.evaluate(() => navigator.maxTouchPoints), "Chromium touch emulation must expose real touch points").toBeGreaterThan(0);
            }
        }
        // Keep actual native browser WebSockets and real network/offline semantics.
        // This guard only blocks nonlocal handshakes and unpermitted START writes.
        await context.addInitScript(
            ({ frontend, backend, paid }) => {
                const NativeWebSocket = window.WebSocket;
                const allowed = [frontend, backend].map((value) => new URL(value).origin.replace(/^http:/, "ws:"));
                const socketPath = new URL(`${backend}/lobbySocket`).pathname;
                let permits = 0;
                let halted = false;
                let lobbySocket: WebSocket | undefined;
                window.__geobattlesE2EPermitStart = () => {
                    if (halted || permits !== 0) throw new Error("E2E refused a halted or overlapping START permit");
                    permits = 1;
                };
                window.__geobattlesE2EHaltStarts = () => {
                    halted = true;
                    permits = 0;
                };
                window.__geobattlesE2EProbeStart = () => {
                    if (!lobbySocket || lobbySocket.readyState !== NativeWebSocket.OPEN) throw new Error("No connected real lobby socket for readiness rejection probe");
                    lobbySocket.send(JSON.stringify({ command: "start" }));
                };
                window.WebSocket = class extends NativeWebSocket {
                    constructor(url: string | URL, protocols?: string | string[]) {
                        const target = new URL(String(url), location.href);
                        // Native WebSocket resolves relative/HTTP URLs to WS(S).
                        // Validate that same effective origin without altering input.
                        if (target.protocol === "http:") target.protocol = "ws:";
                        else if (target.protocol === "https:") target.protocol = "wss:";
                        if (!allowed.includes(target.origin) || target.username || target.password) throw new Error("E2E blocked a nonlocal WebSocket before handshake");
                        super(url, protocols);
                        if (target.origin === allowed[1] && target.pathname === socketPath) lobbySocket = this;
                    }
                    override send(data: string | Blob | BufferSource) {
                        if (typeof data === "string") {
                            let command;
                            try {
                                command = JSON.parse(data).command;
                            } catch {
                                /* Native server validates malformed requests. */
                            }
                            if (command === "start") {
                                if (!paid || halted || permits < 1) throw new Error("E2E blocked an unapproved START before network transmission");
                                permits--;
                            }
                        }
                        super.send(data);
                    }
                };
            },
            { frontend: env.frontend!, backend: env.backend, paid: this.paid }
        );

        // Additional request-level gate only: Playwright does NOT re-route redirect
        // hops. The native per-context proxy below it checks every destination.
        await context.route("**/*", async (route) => {
            const url = new URL(route.request().url());
            const local = [env.frontend, env.backendOrigin].includes(url.origin);
            if (local) return route.continue();
            if (this.paid && isMapsURL(url.href)) {
                if (this.halted || paidBudget.halted) return route.abort("blockedbyclient");
                const failure = this.sdkFailure;
                if (
                    failure?.actor === actor &&
                    !failure.resumed &&
                    url.origin === "https://maps.googleapis.com" &&
                    url.pathname === "/maps/api/js" &&
                    route.request().resourceType() === "script"
                ) {
                    if (failure.request) {
                        this.record(actor, "provider-error", "unrequested-sdk-retry");
                        return route.abort("blockedbyclient");
                    }
                    failure.request = route.request();
                    // Hold only this native script until the real loading UI is
                    // observable, then abort it. No fabricated response or state.
                    try {
                        const status = actor.page.getByTestId("maps-recovery").getByRole("status");
                        await expect(status).toBeVisible({ timeout: 5_000 });
                        await expect(status).toHaveText("Loading the landscape. The clock continues.", { timeout: 5_000 });
                    } catch {
                        this.record(actor, "acceptance-error", "maps-loading-ui-not-observed");
                        return route.abort("blockedbyclient");
                    }
                    failure.deadline = Date.now() + 12_000;
                    // Real browser transport failure before any peer SDK constructors.
                    // No response, Google implementation, state or success is supplied.
                    return route.abort("failed");
                }
                return route.continue();
            }
            this.record(actor, "blocked-request", "unapproved-external-destination");
            await route.abort("blockedbyclient");
        });
        page.on("pageerror", (error) => this.record(actor, "javascript-error", "uncaught", false, error.message));
        page.on("console", (message) => {
            if (!["error", "warning"].includes(message.type())) return;
            if (providerMessage.test(message.text())) {
                this.record(actor, "provider-error", "google-maps", false, message.text());
                return;
            }
            const failure = this.sdkFailureInterval(actor);
            if (
                failure &&
                !failure.consoleError &&
                message.type() === "error" &&
                message.location().url === failure.request!.url() &&
                /^Failed to load resource: net::ERR_FAILED$/.test(message.text())
            ) {
                failure.consoleError = true;
                this.record(actor, "console-error", "deliberate-maps-sdk-abort", true);
                return;
            }
            const expected = actor.offline && networkMessage.test(message.text()) && !/TypeError|ReferenceError|SyntaxError|hydration|Vue warn/i.test(message.text());
            this.record(actor, message.type() === "warning" ? "console-warning" : "console-error", expected ? "offline-network" : "browser-console", expected, message.text());
        });
        page.on("request", (request) => {
            if (request.isNavigationRequest() && request.frame() === page.mainFrame()) actor.documentRequests++;
            if (["guest", "refresh", "auth-other"].includes(resourceKind(request.url(), env.frontend, env.backend))) actor.authRequests++;
            if (isMapsURL(request.url())) {
                this.sdkRequests++;
                if (this.paid) paidBudget.sdkRequests++;
            }
        });
        page.on("requestfailed", (request) => {
            const failure = this.sdkFailureInterval(actor);
            if (failure && !failure.requestFailed && request === failure.request && request.failure()?.errorText === "net::ERR_FAILED") {
                failure.requestFailed = true;
                this.record(actor, "request-failed", "deliberate-maps-sdk-abort", true);
                return;
            }
            const error = request.failure()?.errorText ?? "";
            const aborted = /ERR_ABORTED/i.test(error);
            // Fixed browser error grammar and a finite resource-type vocabulary
            // explain the original failure without keeping URLs, keys or bodies.
            const networkCode = /^(?:net::ERR_[A-Z_]{1,64}|NS_ERROR_[A-Z_]{1,64})$/.test(error) ? error : "other-network-error";
            const type = request.resourceType();
            const requestType = ["document", "stylesheet", "image", "media", "font", "script", "xhr", "fetch", "websocket", "other"].includes(type) ? type : "other";
            const imageCancellation = isMapsImageCancellation(request.url(), type, error, this.paid && !this.halted && !paidBudget.halted && this.viewGrants.size > 0);
            this.record(
                actor,
                "request-failed",
                imageCancellation ? "maps-image-cancelled" : resourceKind(request.url(), env.frontend, env.backend),
                imageCancellation || actor.offline || ((actor.navigating || actor.closing) && aborted),
                undefined,
                undefined,
                networkCode,
                requestType
            );
        });
        page.on("response", (response) => {
            if (response.status() >= 400) this.record(actor, "http-error", resourceKind(response.url(), env.frontend, env.backend), false, undefined, response.status());
        });
        page.on("framenavigated", (frame) => {
            if (frame === page.mainFrame()) actor.mainFrameNavigations++;
        });
        page.on("websocket", (socket) => {
            const url = new URL(socket.url());
            if (url.origin !== lobbySocketURL.origin || url.pathname !== lobbySocketURL.pathname) return;
            const generation = ++actor.generation;
            let seq = 0;
            socket.on("framesent", ({ payload }) => {
                try {
                    if (JSON.parse(String(payload)).command === "start") actor.startCommands++;
                } catch {
                    this.record(actor, "protocol-error", "non-json-outgoing-frame");
                }
            });
            socket.on("socketerror", () => this.record(actor, "socket-error", "lobby-transport", actor.offline || actor.navigating || actor.closing));
            socket.on("framereceived", ({ payload }) => {
                let event: Envelope;
                try {
                    event = JSON.parse(String(payload));
                } catch {
                    this.record(actor, "protocol-error", "non-json-frame");
                    return;
                }
                if ((event as unknown as { command?: string }).command === "ping") return;
                if (!Number.isSafeInteger(event.seq) || event.seq <= seq) this.record(actor, "protocol-error", "sequence-absent-stale-or-reordered");
                seq = event.seq;
                if (actor.events.length >= 512) {
                    this.record(actor, "protocol-error", "event-limit");
                    return;
                }
                actor.events.push({ ...event, generation });
                if (event.type === "START_ROUND") {
                    const { gameId, round, phase } = event.payload ?? {};
                    if (!gameId || !gameIdentity.test(gameId) || !Number.isSafeInteger(round) || round! < 1 || phase !== "PLAYING") {
                        this.record(actor, "protocol-error", "unexpected-real-round-identity");
                        return;
                    }
                    const key = `${gameId}:${round}`;
                    if (!this.started.has(key)) {
                        // Record the observed cost even if the identity/permit is wrong.
                        if (this.paid && paidBudget.started.has(key)) this.record(actor, "protocol-error", "game-identity-reused-across-scenarios");
                        this.started.add(key);
                        if (this.paid) paidBudget.started.add(key);
                        const pending = this.pendingStart;
                        const validGame = round === 1 ? gameId !== this.currentGameId : gameId === this.currentGameId && round === this.currentRound + 1;
                        if (!pending || pending.round !== round || !validGame) this.record(actor, "protocol-error", "start-without-permit-or-consistent-game");
                        this.currentGameId = gameId;
                        this.currentRound = round!;
                        this.roundSequences.set(key, event.seq);
                        this.pendingStart = undefined;
                        if (this.pendingRejection) this.record(actor, "budget-error", "readiness-probe-unexpectedly-started-provider-round");
                    } else if (this.roundSequences.get(key) !== event.seq) this.record(actor, "protocol-error", "duplicate-round-start");
                }
                const snapshot = event.payload?.lobby;
                const phase = snapshot?.phase ?? event.payload?.phase;
                const gameId = snapshot?.gameId ?? event.payload?.gameId;
                const round = snapshot?.round ?? event.payload?.round;
                if (["START_ROUND", "REJOIN_ROUND", "JOINED_LOBBY"].includes(event.type) && phase !== "WAITING" && gameId && round) {
                    // Map+panorama authorization upper bound, not a claim about billable constructor counts.
                    if (!this.started.has(`${gameId}:${round}`)) this.record(actor, "protocol-error", "view-without-observed-real-start");
                    const key = `${this.info.testId}:${actor.index}:${generation}:${gameId}:${round}`;
                    this.viewGrants.add(key);
                    if (this.paid) paidBudget.viewGrants.add(key);
                }
                if (
                    this.paid &&
                    (paidBudget.started.size > env.rounds ||
                        paidBudget.started.size > paidBudget.acceptedPermits ||
                        paidBudget.viewGrants.size * 2 > env.loads ||
                        paidBudget.viewGrants.size * 2 > paidBudget.reservedGrants ||
                        this.viewGrants.size * 2 > this.reservedGrants)
                )
                    this.record(actor, "budget-error", "aggregate-round-or-view-grant-limit");
                if (!this.paid && (this.started.size || this.viewGrants.size)) this.record(actor, "budget-error", "keyless-round-or-view");
                if (event.type === "REQUEST_ERROR") {
                    if (this.pendingRejection === actor && event.payload?.command === "start" && event.payload.code === "PLAYERS_NOT_READY") this.pendingRejection = undefined;
                    else this.record(actor, "server-error", "unexpected-request-error");
                }
            });
        });
        return actor;
    }

    async permitStart(actor: Actor) {
        this.beforeStart(actor);
        const plan = this.plan!;
        expect(this.acceptedPermits, "Scenario has no planned round action remaining").toBeLessThan(plan.rounds.length);
        expect(this.actors).toHaveLength(plan.players);
        const round = plan.rounds[this.acceptedPermits];
        expect(actor.phase).toBe(round === 1 ? (this.currentGameId ? "FINISHED" : "WAITING") : "MID-ROUND");
        if (round === 1)
            expect(
                Object.values(actor.players).every((player) => player.connected && player.ready),
                "All actual retained members must be ready for a new game"
            ).toBe(true);
        else expect(round).toBe(this.currentRound + 1); // No second ready gate in MID-ROUND.
        expect(paidBudget.acceptedPermits).toBeLessThan(Math.min(env.rounds, mapsAllocation.starts));
        expect(paidBudget.started.size).toBeLessThan(env.rounds);
        if (!this.reservedGrants) {
            const allocation = plannedAllocation([plan]);
            expect(paidBudget.reservedGrants + allocation.grants, "Reserve this entire scenario including its one recovery before provider work").toBeLessThanOrEqual(env.loads);
            this.reservedGrants = allocation.grants;
            paidBudget.reservedGrants += allocation.grants;
        }
        expect(paidBudget.viewGrants.size * 2).toBeLessThan(paidBudget.reservedGrants);
        this.acceptedPermits++;
        paidBudget.acceptedPermits++;
        this.startPermits++;
        this.pendingStart = { round };
        await actor.page.evaluate(() => window.__geobattlesE2EPermitStart());
    }

    beforeStart(actor: Actor) {
        expect(this.paid && env.maps, "Maps suite requires explicit opt-in and its project").toBe(true);
        expect(this.halted || paidBudget.halted, "Stop the whole invocation after a provider/network/protocol/selector failure").toBe(false);
        expect(this.plan, "Paid file must have an explicit action allocation").toBeDefined();
        expect(this.pendingStart || this.pendingRejection, "Do not overlap start commands or retry a pending selection").toBeUndefined();
        expect(actor.latest?.admin).toBe(actor.id);
        expect(paidBudget.acceptedPermits + paidBudget.rejectionPermits, "Aggregate positive + negative command allocation is absolute").toBeLessThan(mapsAllocation.commands);
    }

    async probeReadinessRejection(actor: Actor) {
        this.beforeStart(actor);
        expect(["WAITING", "FINISHED"]).toContain(actor.phase);
        expect(
            Object.values(actor.players).some((player) => !player.ready),
            "A negative probe needs actual authoritative unready membership"
        ).toBe(true);
        expect(this.rejectionPermits).toBeLessThan(this.plan!.readinessRejections);
        expect(paidBudget.rejectionPermits).toBeLessThan(mapsAllocation.readinessRejections);
        const mark = actor.mark();
        this.rejectionPermits++;
        paidBudget.rejectionPermits++;
        this.startPermits++;
        this.pendingRejection = actor;
        await actor.page.evaluate(() => window.__geobattlesE2EPermitStart());
        await actor.page.evaluate(() => window.__geobattlesE2EProbeStart());
        await actor.event("REQUEST_ERROR", (event) => event.payload?.command === "start" && event.payload.code === "PLAYERS_NOT_READY", mark);
    }

    assertHealthy() {
        expect(this.halted || (this.paid && paidBudget.halted), "The shared halt flag is sticky across paid cases").toBe(false);
        expect(
            this.diagnostics.filter((event) => !event.expected && event.kind !== "console-warning"),
            "Unexpected JS, HTTP, socket, external-request or protocol error; see sanitized diagnostics"
        ).toEqual([]);
    }

    async evidence() {
        const summary = {
            paid: this.paid,
            successfulRoundStarts: this.started.size,
            permittedStartCommands: this.startPermits,
            permittedAcceptedStarts: this.acceptedPermits,
            permittedReadinessRejections: this.rejectionPermits,
            observedGoogleRequests: this.sdkRequests,
            deliberateInitialSDKAborts: this.sdkFailure?.requestFailed ? 1 : 0,
            mapsRetryNetworkResumed: this.sdkFailure?.resumed ?? false,
            conservativeMapAndPanoramaGrantUpperBound: this.viewGrants.size * 2,
            ...(this.paid
                ? {
                      aggregate: {
                          planned: mapsAllocation,
                          successfulRoundStarts: paidBudget.started.size,
                          permittedAcceptedStarts: paidBudget.acceptedPermits,
                          permittedReadinessRejections: paidBudget.rejectionPermits,
                          permittedStartCommands: paidBudget.acceptedPermits + paidBudget.rejectionPermits,
                          reservedConservativeGrants: paidBudget.reservedGrants,
                          observedConservativeGrants: paidBudget.viewGrants.size * 2,
                          observedGoogleRequests: paidBudget.sdkRequests,
                          halted: paidBudget.halted,
                      },
                  }
                : {}),
            diagnostics: this.diagnostics,
            networkGuard: this.networkGuard ? { ...this.networkGuard.counts } : undefined,
        };
        // Body-only attachments disappear with the privacy-preserving reporter.
        // Persist these curated counters/categories for budget reconciliation.
        const diagnosticPath = this.info.outputPath("sanitized-browser-diagnostics.json");
        await writeFile(diagnosticPath, JSON.stringify(summary, null, 2), { mode: 0o600 });
        await this.info.attach("sanitized-browser-diagnostics", { path: diagnosticPath, contentType: "application/json" });
        if (this.info.status !== this.info.expectedStatus || this.diagnostics.some((event) => !event.expected && event.kind !== "console-warning")) {
            for (const actor of this.actors) {
                try {
                    const path = this.info.outputPath(`actor-${actor.index}-failure.png`);
                    await actor.page.screenshot({
                        path,
                        fullPage: true,
                        mask: [
                            actor.page.locator("input, textarea, [contenteditable], [data-auth], [data-sensitive], pre, code"),
                            actor.page.getByText(
                                /eyJ[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+\.[A-Za-z0-9_-]+|AIza[0-9A-Za-z_-]{20,}|(?:access|refresh)[_-]?token|authorization|cookie\s*[:=]/i
                            ),
                        ],
                        maskColor: "#111827",
                    });
                    await chmod(path, 0o600);
                    await this.info.attach(`actor-${actor.index}-failure`, { path, contentType: "image/png" });
                } catch {
                    // A closed/crashed page has no screenshot; do not log arbitrary errors.
                }
            }
        }
    }
}

export const test = base.extend<{ run: BrowserRun }>({
    run: async ({ browser, browserName }, use, info) => {
        assertRunnerPolicy(info.config); // Before any application context/network activity.
        const paid = info.project.name === "maps";
        expect(info.project.use.trace, "Trace must stay off even with CLI overrides").toBe("off");
        expect(info.project.use.video, "Video must stay off").toBe("off");
        expect(info.project.use.screenshot, "Only fixture-owned masked failure screenshots are allowed").toBe("off");
        if (paid) {
            expect(env.maps).toBe(true);
            expect(mapsTestFiles, "Only files in the explicit paid scope may create players").toContain(basename(info.file));
            expect(info.project.retries, "Paid retries are forbidden").toBe(0);
            expect(info.project.repeatEach, "Paid automatic repetition is forbidden").toBe(1);
            expect(info.config.workers, "Paid execution must remain serial").toBe(1);
            expect(info.config.maxFailures, "A failed test must not spawn a fresh paid worker").toBe(1);
            expect(info.config.shard, "Paid sharding would split the aggregate ledger").toBeNull();
            expect(info.workerIndex, "Paid worker replacement cannot reset the ledger").toBe(0);
            expect(paidBudget.halted, "An earlier paid scenario halted this invocation").toBe(false);
            expect(info.config.projects).toHaveLength(1);
            expect(info.project.use.browserName, "Only the explicit Chromium paid project is authorized").toBe("chromium");
        }
        const run = new BrowserRun(
            info,
            async (mobile, proxyServer) =>
                browser.newContext({
                    baseURL: env.frontend,
                    // Chromium otherwise has an implicit loopback bypass. Firefox
                    // receives its own native context proxy with no bypass entries.
                    proxy: { server: proxyServer, bypass: browserName === "chromium" ? "<-loopback>" : "" },
                    viewport: mobile ? { width: 390, height: 844 } : { width: 1440, height: 1000 },
                    // Firefox does not implement isMobile; omit it entirely.
                    ...(browserName === "firefox" ? {} : { isMobile: mobile }),
                    hasTouch: mobile,
                    serviceWorkers: "block",
                    acceptDownloads: false,
                    ignoreHTTPSErrors: false,
                }),
            paid
        );
        try {
            await run.startNetworkGuard();
            await use(run);
            run.assertHealthy();
        } finally {
            if (info.status !== "passed") run.halt();
            // Evidence first; cleanup may generate expected cancellation events.
            try {
                await run.evidence();
            } finally {
                await run.close(); // Always close every owned context and listener, even after evidence I/O failure.
            }
        }
    },
});

